import assert from 'node:assert/strict';
import { readFile, writeFile, unlink } from 'node:fs/promises';
import ts from 'typescript';
const fixture = new URL('../reference/.finished-goods-ledger.mjs', import.meta.url);
const source = await readFile(new URL('../src/finishedGoods.tsx', import.meta.url), 'utf8');
await writeFile(fixture, ts.transpileModule(source, { compilerOptions: { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText);
try {
  const { initialFinishedState, applyFinishedAction, totalWeight } = await import(fixture.href);
  let state = initialFinishedState();
  const at = '2026-10-20 14:00:00';
  const balance = () => state.boxes.filter(box => box.state === 'stock');
  const invariant = () => {
    const ins = state.inbound.reduce((sum, row) => sum + row.boxes.length, 0);
    const outs = state.outbound.reduce((sum, row) => sum + row.boxes.length, 0);
    const restores = state.outbound.filter(row => row.restoration).reduce((sum, row) => sum + row.boxes.length, 0);
    assert.equal(balance().length, ins - outs + restores, '库存箱数必须与入库、原出库和恢复账目平衡');
    const inWeight = state.inbound.reduce((sum, row) => sum + totalWeight(row.boxes), 0);
    const outWeight = state.outbound.reduce((sum, row) => sum + totalWeight(row.boxes), 0);
    const restoredWeight = state.outbound.filter(row => row.restoration).reduce((sum, row) => sum + totalWeight(row.boxes), 0);
    assert.equal(totalWeight(balance()), inWeight - outWeight + restoredWeight, '标准净重必须与库存账目平衡');
  };
  const act = action => { const next = applyFinishedAction(state, action); if (next.result.ok) state = next.state; invariant(); return next.result; };
  const stock = balance().length;
  invariant();
  assert.equal(act({ type: 'inbound', codes: [], warehouse: '1号冷库', time: at }).ok, false);
  const pending = state.boxes.filter(box => box.state === 'pending');
  assert.equal(act({ type: 'inbound', codes: [pending[0].code], warehouse: '', time: at }).ok, false);
  assert.equal(act({ type: 'inbound', codes: [pending[0].code, pending[8].code], warehouse: '1号冷库', time: at }).ok, false);
  assert.equal(act({ type: 'inbound', codes: [pending[0].code, pending[10].code], warehouse: '1号冷库', time: at }).ok, false);
  assert.equal(balance().length, stock);
  const inbound = act({ type: 'inbound', codes: [pending[0].code, pending[1].code, pending[0].code], warehouse: '1号冷库', time: at });
  assert.equal(inbound.ok, true); assert.equal(balance().length, stock + 2);
  assert.equal(state.pallets[0].codes.length, 2, '重复码不应生成重复箱托关联');
  assert.equal(act({ type: 'inbound', codes: [pending[0].code], warehouse: '1号冷库', time: at }).ok, false);
  const twoCodes = pending.slice(0, 2).map(box => box.code);
  const outbound = act({ type: 'outbound', codes: [...twoCodes, twoCodes[0]], time: at });
  assert.equal(outbound.ok, true); assert.equal(balance().length, stock);
  const original = structuredClone(state.outbound[0]);
  assert.equal(act({ type: 'outbound', codes: twoCodes, time: at }).ok, false);
  assert.equal(act({ type: 'restore', batch: outbound.id, reason: '  ', time: at }).ok, false);
  assert.equal(act({ type: 'restore', batch: outbound.id, reason: '取消发货，货物已回仓', time: at }).ok, true);
  assert.equal(balance().length, stock + 2);
  assert.equal(act({ type: 'restore', batch: outbound.id, reason: '重复恢复', time: at }).ok, false);
  assert.deepEqual(state.outbound.find(row => row.id === outbound.id).boxes, original.boxes, '恢复后原出库清单应保真');
  assert.equal(state.inbound.length, 6, '恢复不应生成首次组托入库记录');
  const resend = act({ type: 'outbound', codes: twoCodes, time: at });
  assert.equal(resend.ok, true); assert.notEqual(resend.id, outbound.id);
  assert.notEqual(state.outbound[0].document, original.document, '再次发货须生成新的出库单');
  const crossWarehouse = balance().find(box => box.warehouse === '2号冷库');
  const firstWarehouse = balance().find(box => box.warehouse === '1号冷库');
  assert.equal(act({ type: 'outbound', codes: [crossWarehouse.code, firstWarehouse.code], time: at }).ok, false);
  assert.equal(act({ type: 'outbound', codes: ['不存在'], time: at }).ok, false);
  console.log('通过：库存箱数和重量守恒、空清单、仓库、混品种、混规格、去重、重复入库/出库/恢复、原单保真及再次发货新批次。');
} finally { await unlink(fixture); }
